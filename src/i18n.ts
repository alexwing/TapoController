export function resolveLang(setting: string): Lang {
  if (
    setting === "es" ||
    setting === "en" ||
    setting === "de" ||
    setting === "fr" ||
    setting === "pt"
  ) {
    return setting;
  }
  const sys = (navigator.language || "en").toLowerCase();
  if (sys.startsWith("es")) return "es";
  if (sys.startsWith("de")) return "de";
  if (sys.startsWith("fr")) return "fr";
  if (sys.startsWith("pt")) return "pt";
  return "en";
}

export function makeT(lang: Lang) {
  return (key: string): string => DICT[lang][key] ?? DICT.en[key] ?? key;
}
